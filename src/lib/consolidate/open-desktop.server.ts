import "server-only";

import { execFile, spawn } from "node:child_process";
import { promises as fs } from "node:fs";
import os from "node:os";
import path from "node:path";
import { promisify } from "node:util";
import { consolidateAppOrigin } from "@/lib/consolidate/urls";

const execFileAsync = promisify(execFile);

type PreferenceBucket = {
  ServerUrl?: string;
  mailto_prompted?: string;
  DarkMode?: string;
  AppLanguage?: string;
  [key: string]: string | undefined;
};

type PreferencesFile = {
  ""?: PreferenceBucket;
};

function localAppData(): string {
  return (
    process.env.LOCALAPPDATA?.trim() ||
    path.join(os.homedir(), "AppData", "Local")
  );
}

function consolidatePaths() {
  const root = path.join(localAppData(), "Consolidate");
  return {
    exe: path.join(root, "current", "Consolidate.App.Windows.exe"),
    stub: path.join(root, "Consolidate.exe"),
    preferences: path.join(
      root,
      "Consolidate",
      "Settings",
      "preferences.dat"
    ),
    helperDir: path.join(localAppData(), "ConsolidateDrive"),
    helperScript: path.join(
      localAppData(),
      "ConsolidateDrive",
      "open-consolidate.ps1"
    ),
  };
}

export function isConsolidateDeepLinkAllowed(
  apiUrl: string,
  candidate: string
): boolean {
  try {
    const origin = consolidateAppOrigin(apiUrl);
    const url = new URL(candidate);
    if (url.protocol !== "https:" && url.protocol !== "http:") return false;
    return url.origin === new URL(origin).origin;
  } catch {
    return false;
  }
}

async function pathExists(filePath: string): Promise<boolean> {
  try {
    await fs.access(filePath);
    return true;
  } catch {
    return false;
  }
}

async function isDesktopAppRunning(): Promise<boolean> {
  if (process.platform !== "win32") return false;
  try {
    const { stdout } = await execFileAsync(
      "tasklist",
      ["/FI", "IMAGENAME eq Consolidate.App.Windows.exe", "/NH"],
      { windowsHide: true }
    );
    return /Consolidate\.App\.Windows\.exe/i.test(stdout);
  } catch {
    return false;
  }
}

async function readPreferences(
  filePath: string
): Promise<PreferencesFile | null> {
  try {
    const raw = await fs.readFile(filePath, "utf8");
    return JSON.parse(raw) as PreferencesFile;
  } catch {
    return null;
  }
}

async function writePreferences(
  filePath: string,
  data: PreferencesFile
): Promise<void> {
  await fs.mkdir(path.dirname(filePath), { recursive: true });
  await fs.writeFile(filePath, JSON.stringify(data), "utf8");
}

function escapeForSingleQuotedPs(value: string): string {
  return value.replace(/'/g, "''");
}

async function ensureProtocolHelper(
  httpsOrigin: string,
  exePath: string
): Promise<void> {
  if (process.platform !== "win32") return;
  const { helperDir, helperScript } = consolidatePaths();
  await fs.mkdir(helperDir, { recursive: true });

  const origin = escapeForSingleQuotedPs(httpsOrigin);
  const exe = escapeForSingleQuotedPs(exePath);

  const script = `# Auto-generated by Consolidate Drive — open consolidate:// links in the desktop app.
param([Parameter(Mandatory = $true)][string]$Uri)
$ErrorActionPreference = 'Stop'
$https = $Uri -replace '^consolidate://', 'https://' -replace '^consolidate:', 'https://'
if ($https -notmatch '^https://') { $https = 'https://' + ($https -replace '^/*','') }

$allowedHost = ([Uri]'${origin}').Host
try {
  $u = [Uri]$https
  if ($u.Host -ne $allowedHost) {
    Start-Process $https
    exit 0
  }
} catch {
  Start-Process $https
  exit 0
}

$exe = '${exe}'
$prefPath = Join-Path $env:LOCALAPPDATA 'Consolidate\\Consolidate\\Settings\\preferences.dat'
$origin = '${origin}'

if (Get-Process -Name 'Consolidate.App.Windows' -ErrorAction SilentlyContinue) {
  Start-Process $https
  exit 0
}

$previous = $origin
$raw = '{{"":{{"ServerUrl":"{0}","mailto_prompted":"True","DarkMode":"False","AppLanguage":"de"}}}}' -f $origin
if (Test-Path $prefPath) {
  try { $raw = Get-Content $prefPath -Raw -Encoding UTF8 } catch {}
  if ($raw -match '"ServerUrl"\\s*:\\s*"([^"]*)"') { $previous = $Matches[1] }
}
if ($raw -match '"ServerUrl"\\s*:') {
  $raw = [regex]::Replace($raw, '"ServerUrl"\\s*:\\s*"[^"]*"', ('"ServerUrl":"' + $https + '"'))
} else {
  $raw = '{{"":{{"ServerUrl":"{0}","mailto_prompted":"True","DarkMode":"False","AppLanguage":"de"}}}}' -f $https
}
$prefDir = Split-Path $prefPath -Parent
if (-not (Test-Path $prefDir)) { New-Item -ItemType Directory -Path $prefDir -Force | Out-Null }
Set-Content -Path $prefPath -Value $raw -Encoding UTF8

Start-Process -FilePath $exe

Start-Job -ScriptBlock {
  param($Path, $Url)
  Start-Sleep -Seconds 8
  try {
    if (-not (Test-Path $Path)) { return }
    $content = Get-Content $Path -Raw -Encoding UTF8
    $content = [regex]::Replace($content, '"ServerUrl"\\s*:\\s*"[^"]*"', ('"ServerUrl":"' + $Url + '"'))
    Set-Content -Path $Path -Value $content -Encoding UTF8
  } catch {}
} -ArgumentList $prefPath, $previous | Out-Null
`;

  await fs.writeFile(helperScript, script, "utf8");

  const command = `powershell.exe -NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -File "${helperScript}" "%1"`;
  const ps = `
$ErrorActionPreference = 'Stop'
$base = 'HKCU:\\Software\\Classes\\consolidate'
New-Item -Path $base -Force | Out-Null
Set-ItemProperty -Path $base -Name '(default)' -Value 'URL:Consolidate Protocol'
New-ItemProperty -Path $base -Name 'URL Protocol' -Value '' -PropertyType String -Force | Out-Null
New-Item -Path "$base\\shell\\open\\command" -Force | Out-Null
Set-ItemProperty -Path "$base\\shell\\open\\command" -Name '(default)' -Value @'
${command}
'@
`;
  await execFileAsync(
    "powershell.exe",
    ["-NoProfile", "-ExecutionPolicy", "Bypass", "-Command", ps],
    { windowsHide: true }
  );
}

function launchDetached(exePath: string): void {
  const child = spawn(exePath, [], {
    detached: true,
    stdio: "ignore",
    windowsHide: false,
  });
  child.unref();
}

/**
 * Launch the local Consolidate desktop app at `targetUrl` when possible.
 * Returns false when the caller should fall back to the browser.
 */
export async function openInConsolidateDesktopApp(options: {
  apiUrl: string;
  targetUrl: string;
}): Promise<{ ok: boolean; reason?: string; protocolRegistered?: boolean }> {
  if (process.platform !== "win32") {
    return { ok: false, reason: "unsupported-platform" };
  }

  const { apiUrl, targetUrl } = options;
  if (!isConsolidateDeepLinkAllowed(apiUrl, targetUrl)) {
    return { ok: false, reason: "untrusted-url" };
  }

  const paths = consolidatePaths();
  const exePath = (await pathExists(paths.exe))
    ? paths.exe
    : (await pathExists(paths.stub))
      ? paths.stub
      : null;
  if (!exePath) {
    return { ok: false, reason: "app-not-installed" };
  }

  const origin = consolidateAppOrigin(apiUrl);

  let protocolRegistered = false;
  try {
    await ensureProtocolHelper(origin, exePath);
    protocolRegistered = true;
  } catch {
    // Protocol registration is best-effort; launching can still succeed.
  }

  if (await isDesktopAppRunning()) {
    return {
      ok: false,
      reason: "already-running",
      protocolRegistered,
    };
  }

  const prefs =
    (await readPreferences(paths.preferences)) ??
    ({
      "": {
        ServerUrl: origin,
        mailto_prompted: "True",
        DarkMode: "False",
        AppLanguage: "de",
      },
    } satisfies PreferencesFile);

  if (!prefs[""]) prefs[""] = {};
  const previousServerUrl = prefs[""].ServerUrl?.trim() || origin;
  prefs[""].ServerUrl = targetUrl;
  await writePreferences(paths.preferences, prefs);

  try {
    launchDetached(exePath);
  } catch {
    prefs[""].ServerUrl = previousServerUrl;
    await writePreferences(paths.preferences, prefs).catch(() => undefined);
    return { ok: false, reason: "launch-failed", protocolRegistered };
  }

  setTimeout(() => {
    void (async () => {
      try {
        const current = (await readPreferences(paths.preferences)) ?? prefs;
        if (!current[""]) current[""] = {};
        current[""].ServerUrl = previousServerUrl;
        await writePreferences(paths.preferences, current);
      } catch {
        // ignore restore errors
      }
    })();
  }, 8000);

  return { ok: true, protocolRegistered };
}
